import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  canVote,
  getFeatureSupport,
  productRegistryV1,
} from "../packages/core/src/product-registry.ts";

// Run with the existing TS loader: node --import tsx scripts/product-docs.mjs [--check].
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node --import tsx scripts/product-docs.mjs [--check]");
}
const root = fileURLToPath(new URL("../", import.meta.url));
const registry = productRegistryV1;
const json = JSON.stringify(registry, null, 2) + "\n";
const revision = createHash("sha256").update(json).digest("hex").slice(0, 12);
const platforms = Object.keys(registry.distributions);
const unestimated = registry.features.filter((feature) => feature.assessment.status === "unestimated").length;
const votable = registry.features.filter((feature) => canVote(registry, feature.id)).length;
const hasVersion = Object.values(registry.distributions).some((item) => item.version !== null);
const labels = {
  web: "Web",
  android: "Android",
  ios: "iPhone",
  macos: "macOS",
  windows: "Windows",
  linux: "Linux",
};
const supportLabels = {
  verified: "Проверено",
  partial: "Частично",
  planned: "Планируется",
  unsupported: "Не поддерживается",
  unverified: "Не проверено",
  unknown: "Неизвестно",
};
const distributionLabels = {
  hosted: "Работающий сайт",
  "private-build": "Приватная сборка",
  "public-release": "Публичный выпуск",
  planned: "Планируется",
  unavailable: "Недоступно",
  unknown: "Неизвестно",
};
const escape = (value) =>
  value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;")
    .replaceAll("|", "\\|").replaceAll("`", "&#96;");
const lines = [
  "# Возможности Aurelia по платформам",
  "",
  "<!-- Generated by scripts/product-docs.mjs; edit packages/core/src/product-registry.ts. -->",
  "",
  `Срез: ${registry.reviewedAt}. Ревизия данных: \`${revision}\`.`,
  "",
  "Источник — [единый реестр](../../packages/core/src/product-registry.ts);",
  "[машиночитаемый снимок](registry.v1.json) содержит те же данные.",
  "Реализация, проверка и доступность разделены. «Проверено» не означает",
  "публичный пакет или работу всего каталога. Условия каждой функции — ниже.",
  hasVersion
    ? "Указанные версии и каналы читаются из реестра; проверка другой версии не переносится автоматически."
    : "Формальные версии пока не назначены; это срез разработки, не описание всех ранее установленных сборок.",
  "",
  "## Каналы и версии",
  "",
  "| Платформа | Доступность | Канал | Формальная версия | Ссылка |",
  "| --- | --- | --- | --- | --- |",
  ...platforms.map((platform) => {
    const item = registry.distributions[platform];
    const link = item.artifact ? `[Открыть](${item.artifact.url})` : "Нет публичного пакета";
    return `| ${labels[platform]} | ${distributionLabels[item.status]} | ${item.channel} | ${item.version ?? "Не назначена"} | ${link} |`;
  }),
  "",
  "## Матрица",
  "",
  "«Частично» требует чтения условий; «Не проверено» и «Неизвестно» не означают",
  "поддержку. Service-запись описывает API, а не готовый экран плеера.",
  "",
  `| Функция | ${platforms.map((platform) => labels[platform]).join(" | ")} |`,
  `| --- | ${platforms.map(() => "---").join(" | ")} |`,
  ...registry.features.map((feature) =>
    `| [${escape(feature.title)}](#${feature.id}) | ${platforms.map((platform) =>
      supportLabels[getFeatureSupport(registry, feature.id, platform)]).join(" | ")} |`),
  "",
  "## Условия и пределы проверок",
  ...registry.features.flatMap((feature) => [
    "",
    `<a id="${feature.id}"></a>`,
    "",
    `### ${escape(feature.title)}`,
    "",
    `${escape(feature.description)} Тип: ${feature.surface}. ID: \`${feature.id}\`.`,
    "",
    ...platforms.map((platform) =>
      `- **${labels[platform]}:** ${escape(feature.platforms[platform].implementation.note)}`),
  ]),
  "",
  "## Будущие функции и участие",
  "",
  `Для ${unestimated} из ${registry.features.length} функций оценки effort, runningCash и maintenance ещё не приняты.`,
  registry.services.voting === "not-connected"
    ? "Голосование не подключено."
    : `Сервис голосования подключён; по оценкам доступно ${votable} карточек. Вход проверяется сервером.`,
  "Финансовая поддержка не подключена; суммы сборов отсутствуют.",
  "Черновые идеи не становятся обязательством или публичным выпуском.",
  "[Порядок развития](../next-milestones.md) и [план публичного сервиса](../product-service-plan.md).",
  "",
];
const outputs = new Map([
  ["docs/product/registry.v1.json", json],
  ["docs/product/features.md", lines.join("\n")],
]);
for (const [relative, content] of outputs) {
  const path = join(root, relative);
  if (args[0] === "--check") {
    const actual = await readFile(path, "utf8").catch(() => null);
    if (actual !== content) {
      process.exitCode = 1;
      process.stderr.write(`Generated product document is stale: ${relative}\n`);
    }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}
if (!process.exitCode) process.stdout.write(`Product docs ${args[0] === "--check" ? "checked" : "generated"}: ${registry.features.length} features, ${platforms.length} platforms, ${revision}\n`);
